#!/usr/bin/env python3
"""gen-axo-faces.py — build systems/axo-faces.js from the Axo face masters.

Masters: the repo-local axo-faces/ folder (vendored 2026-10-24 from the
owner's brand set in ~/workspace/axofy-seo/brand/ — the same glossy dark
robot head in every frame; see axo-ball/FACES.md for the inventory).
The 12 chosen faces: base (the mascot render), blink, halfblink,
thinking, wow, celebrate, sad, angry, pleading, wink, sleep, sleep2.

Each master is resized to 128 px wide (aspect preserved) and re-encoded
as WebP q80, then embedded as a base64 data URI — the same pattern as
systems/balls.js, because the app's push flow cannot ship binary
assets. 128w keeps the sheet face (56–64 px CSS) crisp on retina;
the whole module lands near ~68 KB against balls.js's ~355 KB.

PIL sniffs the real format from content (several brand files carry
extensions that lie about their bytes); masters keep their honest
names here. The 10 original frames have black baked in (RGB); angry
and pleading carry true alpha (RGBA) — both encode fine as WebP.

Usage: python3 scripts/gen-axo-faces.py [masters_dir] [out_file]
Defaults: masters ../axo-faces (relative to the repo root),
out systems/axo-faces.js.
"""
import base64
import io
import os
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTERS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "axo-faces")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, "systems", "axo-faces.js")
WIDTH = 128
QUALITY = 80

# key -> master file (insertion order is the module's key order)
FACES = {
    "base": "base.jpg",
    "blink": "blink.webp",
    "halfblink": "halfblink.webp",
    "thinking": "thinking.webp",
    "wow": "wow.webp",
    "celebrate": "celebrate.webp",
    "sad": "sad.webp",
    "angry": "angry.webp",
    "pleading": "pleading.webp",
    "wink": "wink.webp",
    "sleep": "sleep.webp",
    "sleep2": "sleep2.webp",
}

entries = []
total = 0
for key, name in FACES.items():
    path = os.path.join(MASTERS, name)
    if not os.path.isfile(path):
        sys.exit(f"missing master: {path}")
    img = Image.open(path)
    img.load()
    h = round(img.height * WIDTH / img.width)
    small = img.resize((WIDTH, h), Image.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, format="WEBP", quality=QUALITY, method=6)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    total += len(b64)
    entries.append(f"    {key}: 'data:image/webp;base64,{b64}'")

body = ",\n".join(entries)
js = f"""/* GENERATED by scripts/gen-axo-faces.py — do not edit by hand.
 * Source: the Axo face masters vendored in axo-faces/ (the owner's
 * brand set), resized to 128px wide and embedded as WebP data URIs.
 * Regenerate: python3 scripts/gen-axo-faces.py
 */
(function (global) {{
  'use strict';
  var FACES = {{
{body}
  }};
  global.__O101_AXO_FACES = FACES;
  /** Data URI for a face key ('base', 'wow', …) or null when unknown. */
  global.axoFaceUri = function (name) {{
    return Object.prototype.hasOwnProperty.call(FACES, name) ? FACES[name] : null;
  }};
}})(typeof window !== 'undefined' ? window : globalThis);
"""
with open(OUT, "w", encoding="utf-8") as f:
    f.write(js)
print(f"wrote {OUT}: {len(FACES)} faces, {total} base64 chars, {os.path.getsize(OUT)} bytes total")
