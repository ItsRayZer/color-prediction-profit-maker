#!/usr/bin/env python3
"""gen-balls.py — build systems/balls.js from the owner's OG WinGo ball masters.

Masters: ~/workspace/0101-v2/balls/ball_0.png … ball_9.png (256×256
transparent PNGs cut from the owner's own screenshot of the real DhaniWin
WinGo board — genuine pixels, not redraws). Each master is downscaled to
128×128 and embedded as a base64 data URI: the 256px set would weigh
~1.1MB as base64; the 128px set ships at a fraction of that while staying
crisp at every size the app renders (16–44px, 2x headroom included).

Usage: python3 scripts/gen-balls.py [masters_dir] [out_file]
Defaults: masters ../balls (relative to the repo root), out systems/balls.js.
The PNG masters stay in the workspace — only this text module is committed.
"""
import base64
import io
import os
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTERS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "..", "balls")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, "systems", "balls.js")
SIZE = 128

entries = []
total = 0
for n in range(10):
    path = os.path.join(MASTERS, f"ball_{n}.png")
    if not os.path.isfile(path):
        sys.exit(f"missing master: {path}")
    img = Image.open(path)
    if img.size != (256, 256):
        sys.exit(f"{path}: expected 256x256, got {img.size}")
    if img.mode != "RGBA":
        img = img.convert("RGBA")
    small = img.resize((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, format="PNG", optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode("ascii")
    total += len(b64)
    entries.append(f"    {n}: 'data:image/png;base64,{b64}'")

body = ",\n".join(entries)
js = f"""/* GENERATED by scripts/gen-balls.py — do not edit by hand.
 * Source: the owner's OG WinGo ball masters (balls/ball_0..9.png, 256×256
 * transparent PNGs cut from the real DhaniWin board), downscaled to
 * 128×128 and embedded as data URIs. Regenerate: python3 scripts/gen-balls.py
 */
(function (global) {{
  'use strict';
  var BALLS = {{
{body}
  }};
  global.O101_BALLS = BALLS;
  /**
   * <img> string for result number n at sizePx (extra CSS classes via cls).
   * Returns '' when no image exists for n — callers MUST fall back to their
   * CSS-ball markup on '', so a missing asset can never blank a result.
   */
  global.ballImg = function (n, sizePx, cls) {{
    var uri = BALLS[n];
    if (!uri) return '';
    var s = sizePx || 24;
    return '<img src="' + uri + '" alt="' + n + '" data-ball="' + n + '" width="' + s + '" height="' + s + '" class="ball-3d rounded-full ' + (cls || '') + '" style="width:' + s + 'px;height:' + s + 'px" draggable="false">';
  }};
}})(typeof window !== 'undefined' ? window : globalThis);
"""
with open(OUT, "w", encoding="utf-8") as f:
    f.write(js)
print(f"wrote {OUT}: 10 balls, {total} base64 chars, {os.path.getsize(OUT)} bytes total")
